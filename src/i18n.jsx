const I18nContext = createContext(null);
export const useI18n = () => useContext(I18nContext);

export function I18nProvider({ children }) {
  const [lang, setLang] = useStoredState('relay.ai.lang.v1', String(navigator.language || '').toLowerCase().startsWith('ru') ? 'ru' : 'en');
  const value = useMemo(() => {
    const locale = lang === 'ru' ? 'ru-RU' : 'en-US';
    const nf = new Intl.NumberFormat(locale);
    const df = new Intl.DateTimeFormat(locale, { day: 'numeric', month: 'long', year: 'numeric' });
    const dtf = new Intl.DateTimeFormat(locale, { day: '2-digit', month: '2-digit', year: 'numeric', hour: '2-digit', minute: '2-digit' });
    const t = (key, vars) => {
      let s = translations[lang]?.[key] ?? translations.ru[key] ?? key;
      if (vars) for (const [name, v] of Object.entries(vars)) s = s.replaceAll(`{${name}}`, v);
      return s;
    };
    const translateError = message => {
      const msg = String(message ?? '');
      if (lang === 'ru') return msg;
      const key = errorKeys[msg];
      if (key) return translations.en[key];
      const http = /^(Провайдер|Сервер) вернул HTTP (\d{3})$/.exec(msg);
      if (http) return `${http[1] === 'Провайдер' ? 'Provider' : 'Server'} returned HTTP ${http[2]}`;
      return msg;
    };
    return { lang, setLang, locale, nf, df, dtf, t, translateError };
  }, [lang, setLang]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}
